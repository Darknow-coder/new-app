// Pre-computes adventure levels beyond the main pack into js/levels-more.js (loaded lazily).
//   node scripts/build-more-levels.mjs 2000        → levels 321..2000, using every CPU core
// Each worker writes a part file; the parts are merged at the end.
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { cpus } from 'node:os';
import { fork } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { encodeLevel } from '../js/engine.js';
import { generateAdventureLevel, LEVEL_GENERATOR_VERSION } from '../js/levels.js';
import { LEVEL_DATA } from '../js/levels-data.js';

const CODE = { up: 'U', down: 'D', left: 'L', right: 'R' };
const START = LEVEL_DATA.length + 1;
const tmp = new URL('../.levels-tmp/', import.meta.url);

if (process.argv[2] === '--worker') {
  // Worker k of m: every m-th level of a shuffled order (so slow boss levels are shared), resumable.
  const [k, m, end] = process.argv.slice(3).map(Number);
  const file = new URL(`part-${k}.txt`, tmp);
  const done = {};
  for (let j = 0; j < 64; j++) {
    const f = new URL(`part-${j}.txt`, tmp);
    if (existsSync(f)) for (const l of readFileSync(f, 'utf8').split('\n').filter(Boolean)) done[l.split('\t')[0]] = 1;
  }
  for (let n = START; n <= end; n++) {
    if (Math.floor((n - START) / 7) % m !== k || done[n]) continue;
    const l = generateAdventureLevel(n);
    writeFileSync(file, `${n}\t${encodeLevel(l).join('/')}|${l.par}|${l.solution.map((d) => CODE[d]).join('')}\n`, { flag: 'a' });
  }
  process.exit(0);
}

const END = Number(process.argv[2] || 2000);
mkdirSync(tmp, { recursive: true });
const m = Math.max(1, cpus().length);
const t0 = Date.now();
await Promise.all(
  Array.from({ length: m }, (_, k) => new Promise((res, rej) => fork(fileURLToPath(import.meta.url), ['--worker', k, m, END]).on('exit', (c) => (c ? rej(new Error(`worker ${k} failed`)) : res())))),
);
const byN = {};
for (let k = 0; k < 64; k++) {
  const f = new URL(`part-${k}.txt`, tmp);
  if (existsSync(f)) for (const l of readFileSync(f, 'utf8').split('\n').filter(Boolean)) byN[l.split('\t')[0]] = l.split('\t')[1];
}
const out = [];
for (let n = START; n <= END; n++) {
  if (!byN[n]) throw new Error(`level ${n} missing`);
  out.push(`  '${byN[n]}',`);
}
writeFileSync(
  new URL('../js/levels-more.js', import.meta.url),
  `// Generated by scripts/build-more-levels.mjs (generator v${LEVEL_GENERATOR_VERSION}) — do not edit by hand.\n` +
    `// Adventure levels ${START}-${END}, loaded after start-up. Same format as levels-data.js.\nexport const MORE_START = ${START};\nexport const MORE_DATA = [\n${out.join('\n')}\n];\n`,
);
console.log(`wrote levels ${START}-${END} in ${((Date.now() - t0) / 60000).toFixed(1)} min`);
